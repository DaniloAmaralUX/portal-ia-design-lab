export function lessonUrl(courseUrl: string, lesson: Lesson): string {
  return `${courseUrl}/${lesson.slug}`;
}

export function lessonsForStep(step: CourseStep): Lesson[] {
  const lessons = LESSONS[step.courseId] ?? [];
  if (!step.slice) return lessons;
  const start = lessons.findIndex((a) => a.slug === step.slice?.from);
  const end = lessons.findIndex((a) => a.slug === step.slice?.to);
  return start >= 0 && end >= start ? lessons.slice(start, end + 1) : [];
}
